import type { Trajectory } from "./artifact"

const strategyOrder = ["oracle", "blind", "regex", "supervisor"] as const

type CanaryInput = Pick<
  Trajectory,
  | "taskID"
  | "strategy"
  | "firstBoundaryResolved"
  | "firstBoundaryFixRate"
  | "resolved"
  | "fixRate"
  | "continuationCount"
  | "redundantTurns"
  | "promptTokens"
  | "completionTokens"
  | "costUSD"
  | "latencyMS"
  | "unsafeContinuationCount"
> & {
  readonly modelRequests: ReadonlyArray<{ readonly kind: "worker" | "controller" }>
}

export interface CanaryAblationRow {
  readonly strategy: (typeof strategyOrder)[number]
  readonly taskID: string
  readonly firstBoundaryResolved: boolean
  readonly finalResolved: boolean
  readonly firstBoundaryFixRate: number
  readonly finalFixRate: number
  readonly resolvedGain: number
  readonly continuationCount: number
  readonly redundantTurns: number
  readonly workerRequests: number
  readonly controllerRequests: number
  readonly promptTokens: number
  readonly completionTokens: number
  readonly totalTokens: number
  readonly costUSD: number
  readonly latencyMS: number
  readonly unsafeContinuationCount: number
}

export function analyzeCanaryAblation(records: ReadonlyArray<CanaryInput>): CanaryAblationRow[] {
  if (
    records.length !== strategyOrder.length ||
    strategyOrder.some((strategy) => records.filter((record) => record.strategy === strategy).length !== 1)
  )
    throw new Error("Canary ablation requires each frozen strategy exactly once")
  if (new Set(records.map((record) => record.taskID)).size !== 1)
    throw new Error("Canary ablation records must use the same task")

  return strategyOrder.map((strategy) => {
    const record = records.find((item) => item.strategy === strategy)
    if (!record) throw new Error(`Missing canary strategy: ${strategy}`)
    return {
      strategy,
      taskID: record.taskID,
      firstBoundaryResolved: record.firstBoundaryResolved,
      finalResolved: record.resolved,
      firstBoundaryFixRate: record.firstBoundaryFixRate,
      finalFixRate: record.fixRate,
      resolvedGain: record.fixRate - record.firstBoundaryFixRate,
      continuationCount: record.continuationCount,
      redundantTurns: record.redundantTurns,
      workerRequests: record.modelRequests.filter((request) => request.kind === "worker").length,
      controllerRequests: record.modelRequests.filter((request) => request.kind === "controller").length,
      promptTokens: record.promptTokens,
      completionTokens: record.completionTokens,
      totalTokens: record.promptTokens + record.completionTokens,
      costUSD: record.costUSD,
      latencyMS: record.latencyMS,
      unsafeContinuationCount: record.unsafeContinuationCount,
    }
  })
}

export function renderCanaryCSV(rows: ReadonlyArray<CanaryAblationRow>) {
  const header = [
    "strategy",
    "first_boundary_resolved",
    "final_resolved",
    "resolved_gain",
    "continuations",
    "redundant_turns",
    "worker_requests",
    "controller_requests",
    "prompt_tokens",
    "completion_tokens",
    "total_tokens",
    "cost_usd",
    "latency_ms",
    "unsafe_continuations",
  ]
  return (
    [
      header.join(","),
      ...rows.map((row) =>
        [
          row.strategy,
          row.firstBoundaryResolved,
          row.finalResolved,
          row.resolvedGain,
          row.continuationCount,
          row.redundantTurns,
          row.workerRequests,
          row.controllerRequests,
          row.promptTokens,
          row.completionTokens,
          row.totalTokens,
          row.costUSD.toFixed(7),
          row.latencyMS,
          row.unsafeContinuationCount,
        ].join(","),
      ),
    ].join("\n") + "\n"
  )
}

export function renderCanaryLatex(rows: ReadonlyArray<CanaryAblationRow>) {
  const label = (strategy: CanaryAblationRow["strategy"]) =>
    strategy === "oracle" ? "Oracle" : strategy === "blind" ? "Blind" : strategy === "regex" ? "Regex" : "Supervisor"
  return (
    rows
      .map((row) =>
        [
          label(row.strategy),
          Number(row.firstBoundaryResolved),
          Number(row.finalResolved),
          row.resolvedGain,
          row.continuationCount,
          row.redundantTurns,
          row.workerRequests,
          row.controllerRequests,
          row.totalTokens,
          row.costUSD.toFixed(4),
          (row.latencyMS / 1000).toFixed(1),
        ].join(" & ") + " \\\\",
      )
      .join("\n") + "\n"
  )
}

export function renderCanaryLatexTable(rows: ReadonlyArray<CanaryAblationRow>) {
  const taskID = rows[0]?.taskID
  if (!taskID) throw new Error("Canary table requires at least one row")
  const body = renderCanaryLatex(rows)
    .trimEnd()
    .split("\n")
    .map((line) => `    ${line}`)
    .join("\n")
  return `% Generated by packages/autodrive-eval/scripts/canary-ablation.ts.\n\\begin{table*}[t]\n  \\caption{Single-task v1.13 paid canary ablation on \\texttt{${escapeLatex(taskID)}}. The four rows are independent, unpaired trajectories and are descriptive only. First and Final are binary resolution outcomes; Gain is the Fix Rate change from the trajectory's own first boundary.}\n  \\label{tab:canary-ablation}\n  \\centering\n  \\small\n  \\begin{tabular}{lrrrrrrrrrr}\n    \\toprule\n    Policy & First & Final & Gain & Cont. & Redun. & Worker & Ctrl. & Tokens & USD & Sec. \\\\\n    \\midrule\n${body}\n    \\bottomrule\n  \\end{tabular}\n\\end{table*}\n`
}

function escapeLatex(value: string) {
  return [...value]
    .map((character) => {
      if (character === "\\") return "\\textbackslash{}"
      if (character === "^") return "\\textasciicircum{}"
      if (character === "~") return "\\textasciitilde{}"
      if ("#$%&_{}".includes(character)) return `\\${character}`
      return character
    })
    .join("")
}
